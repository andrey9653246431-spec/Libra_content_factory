def pulse_line(seed_index: int) -> dict[str, str]:
    return PULSE_LINES[seed_index % len(PULSE_LINES)]


def pulse_compat(weekday_name: str) -> tuple[tuple[str, str], tuple[str, str]]:
    key = weekday_name.lower().strip()
    best = PULSE_BEST.get(key, ("Близнецы", "Водолей"))
    worst = PULSE_WORST.get(key, ("Рак", "Козерог"))
    return best, worst


def pulse_cta(seed_index: int) -> str:
    return PULSE_CTAS[seed_index % len(PULSE_CTAS)]
